//! Free-to-play map zones: the 8x8 tiles the engine lists in
//! `content/maps/free2play.csv` (revision 274), level ignored.
//!
//! A tile is F2P when its zone key `((x >> 3) & 0x7ff) | (((z >> 3)
//! & 0x7ff) << 11)` is listed, exactly like the server check
//! (`GameMap.isFreeToPlay` forces level 0, so upper floors and
//! dungeons inherit their map square). The ranges below are the
//! sorted CSV entries packed into runs; their union is the CSV
//! set (6747 zones). Regenerate from the CSV, never by hand:
//! parse each `level_mapx_mapz_lx_lz` line, keep level 0 rows,
//! pack `((mx*64+lx) >> 3, (mz*64+lz) >> 3)` into ranges.

/// True when this tile stands in an F2P zone (any level).
pub fn is_free(x: i64, z: i64) -> bool {
    let key = (((x >> 3) & 0x7ff) as u32) | ((((z >> 3) & 0x7ff) as u32) << 11);
    RANGES.binary_search_by(|&(low, high)| {
        if key < low {
            std::cmp::Ordering::Greater
        } else if key > high {
            std::cmp::Ordering::Less
        } else {
            std::cmp::Ordering::Equal
        }
    }).is_ok()
}

