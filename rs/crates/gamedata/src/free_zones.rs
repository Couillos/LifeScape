#[cfg(test)]
mod tests {
    use super::{is_free, RANGES};

    #[test]
    fn ranges_cover_the_csv_set() {
        // 6747 CSV lines, all level 0 and 8-aligned, pack into
        // disjoint sorted runs with no gaps inside a run.
        let covered: u32 = RANGES.iter().map(|&(low, high)| high - low + 1).sum();
        assert_eq!(covered, 6747, "csv zone count, got {covered}");
        for pair in RANGES.windows(2) {
            assert!(pair[0].1 + 1 < pair[1].0, "runs disjoint and sorted");
        }
    }

    #[test]
    fn known_tiles() {
        // F2P market and training grounds stay inside; the
        // members towns from the report stay outside.
        for (x, z) in [(3213, 3429), (3200, 3200), (3186, 3440), (3019, 3760), (2987, 3686)] {
            assert!(is_free(x, z), "free tile ({x}, {z})");
        }
        for (x, z) in [(2540, 3090), (2721, 3494), (2568, 3277), (2820, 2990), (2500, 3500)] {
            assert!(!is_free(x, z), "members tile ({x}, {z})");
        }
    }
}
