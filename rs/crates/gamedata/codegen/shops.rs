//! Build-time codegen for `shops.json`: the dict holds two arrays
//! (`shops`, `keepers`), flattened into two statics of the same shape.
//! The caller joins keepers onto shops by exact shop name, like before.

/// Required string field, empty when the dump says nothing (like before).
fn render_req_str(row: &crate::workspace_json::Value, key: &str) -> String {
    format!("\"{}\"", crate::escape_for_rust_literal(row.get(key).as_str().unwrap_or("")))
}

/// `size` reads as int-or-string in the dump (`"40"`).
fn shop_size(row: &crate::workspace_json::Value) -> i64 {
    match row.get("size") {
        crate::workspace_json::Value::Int(value) => *value,
        crate::workspace_json::Value::Float(value) => *value as i64,
        crate::workspace_json::Value::Str(text) => text.parse::<i64>().unwrap_or(0),
        _ => 0,
    }
}

/// `restock` reads as `"yes"`/`"true"`/`"1"` (case-insensitive), like before.
fn shop_restock(row: &crate::workspace_json::Value) -> bool {
    row.get("restock").as_str().is_some_and(|text| matches!(text.to_lowercase().as_str(), "yes" | "true" | "1"))
}

fn render_stocks(row: &crate::workspace_json::Value) -> String {
    let mut rendered = String::from("&[");
    let mut first = true;
    if let crate::workspace_json::Value::Arr(items) = row.get("stocks") {
        for item in items {
            if !first {
                rendered.push_str(", ");
            }
            first = false;
            rendered.push_str(&format!(
                "super::StaticStock {{ obj: {}, count: {}, rate: {} }}",
                render_req_str(item, "obj"),
                item.get("count").as_i64().unwrap_or(1),
                item.get("rate").as_i64().unwrap_or(0),
            ));
        }
    }
    rendered.push(']');
    rendered
}

fn render_shop(row: &crate::workspace_json::Value) -> String {
    format!(
        "    super::StaticShop {{ name: {}, scope: {}, size: {}, restock: {}, stocks: {} }},\n",
        render_req_str(row, "name"),
        crate::render_opt_str(row.get("scope")),
        shop_size(row),
        shop_restock(row),
        render_stocks(row),
    )
}

fn render_opt_i64(row: &crate::workspace_json::Value, key: &str) -> String {
    match row.get(key).as_i64() {
        Some(value) => format!("Some({value})"),
        None => String::from("None"),
    }
}

fn render_keeper(row: &crate::workspace_json::Value) -> String {
    format!(
        "    super::StaticKeeper {{ npc: {}, npc_id: {}, shop: {}, sell: {}, buy: {}, title: {} }},\n",
        render_req_str(row, "npc"),
        row.get("npc_id").as_i64().unwrap_or(-1),
        render_req_str(row, "shop"),
        render_opt_i64(row, "sell_multiplier"),
        render_opt_i64(row, "buy_multiplier"),
        crate::render_opt_str(row.get("title")),
    )
}

/// Render `shops_generated.rs` from the parsed dump.
pub fn generate(manifest_dir: &str) {
    let parsed = crate::parse_dump(manifest_dir, "shops");
    let (shops, keepers) = match &parsed {
        crate::workspace_json::Value::Obj(fields) => (
            match fields.get("shops") {
                Some(crate::workspace_json::Value::Arr(rows)) => rows.clone(),
                _ => Vec::new(),
            },
            match fields.get("keepers") {
                Some(crate::workspace_json::Value::Arr(rows)) => rows.clone(),
                _ => Vec::new(),
            },
        ),
        _ => panic!("shops dump must be a JSON object holding shops and keepers"),
    };
    let mut generated = String::from(
        "// Generated by rs/crates/gamedata/build.rs from gamedata/data/shops.json - do not edit.\n\
         pub static SHOPS: &[super::StaticShop] = &[\n",
    );
    for row in &shops {
        generated.push_str(&render_shop(row));
    }
    generated.push_str("];\npub static KEEPERS: &[super::StaticKeeper] = &[\n");
    for row in &keepers {
        generated.push_str(&render_keeper(row));
    }
    generated.push_str("];\n");
    crate::emit_generated("shops_generated.rs", &generated);
}
