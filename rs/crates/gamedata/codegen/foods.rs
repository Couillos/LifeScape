//! Build-time codegen for `foods.json`: the heal table plus the live-name
//! resolution index. Live callers pass display names ("Shrimps") while the
//! table keys are internal ("shrimp"), so the index maps every lowercase
//! internal name and display name from `objs.json` to its internal key,
//! first dump row winning exactly like the old runtime scan.

/// Render `foods_generated.rs` from the parsed dumps.
pub fn generate(manifest_dir: &str) {
    let parsed = crate::parse_dump(manifest_dir, "foods");
    let fields = match &parsed {
        crate::workspace_json::Value::Obj(fields) => fields,
        _ => panic!("foods dump must be a JSON object of heals"),
    };
    let mut generated = String::from(
        "// Generated by rs/crates/gamedata/build.rs from gamedata/data/foods.json - do not edit.\n\
         pub static ALL: &[(&str, i64)] = &[\n",
    );
    for (name, value) in fields {
        let heal = value.as_i64().unwrap_or(0);
        generated.push_str(&format!("    (\"{}\", {heal}),\n", crate::escape_for_rust_literal(name)));
    }
    generated.push_str("];\n");

    let objs_parsed = crate::parse_dump(manifest_dir, "objs");
    let mut aliases: std::collections::HashMap<String, String> = std::collections::HashMap::new();
    for row in crate::dump_rows(&objs_parsed, "objs") {
        if row.is_null() {
            continue;
        }
        let Some(internal) = row.get("name").as_str() else {
            continue;
        };
        aliases.entry(internal.to_lowercase()).or_insert_with(|| internal.to_string());
        if let Some(display) = row.get("display").as_str() {
            aliases.entry(display.to_lowercase()).or_insert_with(|| internal.to_string());
        }
    }
    let mut sorted: Vec<(&String, &String)> = aliases.iter().collect();
    sorted.sort_by(|left, right| left.0.cmp(right.0));
    generated.push_str("pub static ALIASES: &[(&str, &str)] = &[\n");
    for (alias, key) in sorted {
        generated.push_str(&format!(
            "    (\"{}\", \"{}\"),\n",
            crate::escape_for_rust_literal(alias),
            crate::escape_for_rust_literal(key)
        ));
    }
    generated.push_str("];\n");
    crate::emit_generated("foods_generated.rs", &generated);
}
