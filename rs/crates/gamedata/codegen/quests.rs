/// Render `quests_generated.rs` from the parsed dump.
pub fn generate(manifest_dir: &str) {
    let parsed = crate::parse_dump(manifest_dir, "quests");
    let rows = crate::dump_rows(&parsed, "quests");
    let mut generated = String::from(
        "// Generated by rs/crates/gamedata/build.rs from gamedata/data/quests.json - do not edit.\n\
         pub static ALL: &[super::StaticQuest] = &[\n",
    );
    for row in rows {
        generated.push_str(&format!(
            "    super::StaticQuest {{ name: \"{}\", files: {}, varps: {}, skill_reqs: {}, item_checks: {}, \
             qp_gates: {}, xp_rewards: {}, complete_raw: {}, members: {} }},\n",
            crate::escape_for_rust_literal(row.get("quest").as_str().unwrap_or("")),
            row.get("files").as_i64().unwrap_or(0),
            crate::render_str_array(row, "varps"),
            render_skill_reqs(row),
            render_item_checks(row),
            render_qp_gates(row),
            render_xp_rewards(row),
            crate::render_str_array(row, "complete_raw"),
            crate::render_opt_flag(row, "members"),
        ));
    }
    generated.push_str("];\n");
    crate::emit_generated("quests_generated.rs", &generated);
}
