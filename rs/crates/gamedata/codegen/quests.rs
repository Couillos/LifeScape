//! Build-time codegen for `quests.json`: dump order kept, nested rows as
//! tuples. A null row renders the same defaults the old reader produced.

fn render_skill_reqs(row: &crate::workspace_json::Value) -> String {
    let mut rendered = String::from("&[");
    let mut first = true;
    if let crate::workspace_json::Value::Arr(items) = row.get("skill_reqs") {
        for item in items {
            if !first {
                rendered.push_str(", ");
            }
            first = false;
            rendered.push_str(&format!(
                "({}, {}, {})",
                format!("\"{}\"", crate::escape_for_rust_literal(item.get("skill").as_str().unwrap_or(""))),
                format!("\"{}\"", crate::escape_for_rust_literal(item.get("op").as_str().unwrap_or(""))),
                item.get("level").as_i64().unwrap_or(0),
            ));
        }
    }
    rendered.push(']');
    rendered
}

