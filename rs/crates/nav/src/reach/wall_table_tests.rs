#[test]
fn reach_wall_equals_the_engine_table() {
    let mut mismatches = Vec::new();
    for (shape, angle, flag_index, expected) in TABLE {
        let flag = FLAGS[flag_index];
        let get_flag = move |_x: i32, _z: i32, _level: i32| flag;
        let mut got = String::new();
        for dz in (-2..=2).rev() {
            for dx in -2..=2 {
                got.push(if reach_wall(&get_flag, 0, 10 + dx, 10 + dz, 10, 10, shape, angle) { '1' } else { '0' });
            }
        }
        if got != expected {
            mismatches.push(format!("shape {shape} angle {angle} flag {flag_index}: got {got} engine {expected}"));
        }
        // `reached` takes the wall arm for these shapes, same answers.
        let mut through_reached = String::new();
        for dz in (-2..=2).rev() {
            for dx in -2..=2 {
                through_reached.push(if reached(&get_flag, 0, 10 + dx, 10 + dz, 10, 10, 1, 1, angle, shape, 0) { '1' } else { '0' });
            }
        }
        if through_reached != expected {
            mismatches.push(format!("reached: shape {shape} angle {angle} flag {flag_index}: got {through_reached} engine {expected}"));
        }
    }
    assert!(mismatches.is_empty(), "{} rows differ, first: {:?}", mismatches.len(), &mismatches[..mismatches.len().min(5)]);
}

#[test]
fn the_table_has_both_answers_and_every_shape() {
    let ones: usize = TABLE.iter().map(|row| row.3.matches('1').count()).sum();
    let zeros: usize = TABLE.iter().map(|row| row.3.matches('0').count()).sum();
    assert!(ones > 400 && zeros > 400, "ones {ones} zeros {zeros}");
    for shape in [0, 1, 2, 3, 9] {
        assert!(TABLE.iter().any(|row| row.0 == shape));
    }
    // The diagonal-corner shapes (1, 3) never answer off their own tile.
    for row in TABLE.iter().filter(|row| row.0 == 1 || row.0 == 3) {
        assert_eq!(row.3.matches('1').count(), 1, "{row:?}");
    }
}
