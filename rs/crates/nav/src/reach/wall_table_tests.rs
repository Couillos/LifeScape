//! it ports without being restructured (cyclomatic complexity 87: every
//! arm is the engine's, kept as is).
//!
//! Each row: (shape, angle, flag index, 25 answers). The destination is
//! the wall's tile; the stander is on `dest + (dx, dz)` for dz from +2
//! down to -2 (rows) and dx from -2 to +2 (columns), read left to right,
//! top to bottom. Regenerate with a bun script that loops the engine's
//! `ReachStrategy.reached(stub, 0, 10 + dx, 10 + dz, 10, 10, 1, 1, 1,
//! angle, shape, 0)` over the same grid, with the flag values below
//! (engine `CollisionFlag`: BLOCK_* 0x240120 / 0x240180 / 0x240102 /
//! 0x240108, WALL_* 0x2 / 0x8 / 0x20 / 0x80).

